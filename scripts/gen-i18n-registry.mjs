// Scans packages/i18n/*.json and writes packages/i18n/registry.generated.ts.
// Adding a language = drop a new <code>.json file (with a "_meta" block) + run this script.
// It runs automatically before `npm run dev` and `npm run build`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "packages", "i18n");
const ORDER = ["ru", "kk", "en", "zh", "uz", "ky", "ko", "ja", "hi", "ar"]; // language switcher order (TZ section 3)

const codes = readdirSync(dir)
  .filter((f) => /^[a-z]{2,3}\.json$/.test(f))
  .map((f) => f.replace(".json", ""))
  .sort((a, b) => {
    const ia = ORDER.indexOf(a);
    const ib = ORDER.indexOf(b);
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.localeCompare(b);
  });

for (const c of codes) {
  const meta = JSON.parse(readFileSync(join(dir, `${c}.json`), "utf8"))._meta;
  if (!meta || meta.code !== c) throw new Error(`${c}.json: "_meta.code" must equal "${c}"`);
}

const body = `// AUTO-GENERATED by scripts/gen-i18n-registry.mjs. Do not edit by hand.
${codes.map((c) => `import ${c} from "./${c}.json";`).join("\n")}

export const dictionaries = { ${codes.join(", ")} } as const;
export const localeCodes = ${JSON.stringify(codes)} as const;
`;
writeFileSync(join(dir, "registry.generated.ts"), body);
console.log(`i18n registry: ${codes.length} locales -> ${codes.join(", ")}`);
